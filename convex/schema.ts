import { authTables } from "@convex-dev/auth/server"
import { defineSchema, defineTable } from "convex/server"
import { v } from "convex/values"

export default defineSchema({
  ...authTables,
  profiles: defineTable({
    userId: v.id("users"),
    displayName: v.optional(v.string()),
    role: v.union(
      v.literal("admin"),
      v.literal("mentor"),
      v.literal("lead_scout"),
      v.literal("pit"),
      v.literal("tech"),
      v.literal("scout"),
      v.literal("scouter"),
    ),
  }).index("userId", ["userId"]),
  appSettings: defineTable({
    key: v.string(),
    value: v.string(),
    updatedAt: v.number(),
    updatedBy: v.id("users"),
  }).index("key", ["key"]),
  events: defineTable({
    eventKey: v.string(),
    name: v.string(),
    week: v.optional(v.number()),
    city: v.optional(v.string()),
    state: v.optional(v.string()),
    country: v.optional(v.string()),
    importedAt: v.number(),
    importedBy: v.id("users"),
  }).index("eventKey", ["eventKey"]),
  teams: defineTable({
    eventId: v.id("events"),
    tbaTeamKey: v.string(),
    teamNumber: v.number(),
    nickname: v.string(),
    eventRank: v.optional(v.number()),
    city: v.optional(v.string()),
    state: v.optional(v.string()),
    country: v.optional(v.string()),
    pitStatus: v.union(v.literal("not_scouted"), v.literal("scouted")),
    pickTier: v.union(
      v.literal("tier1"),
      v.literal("tier2"),
      v.literal("tier3"),
      v.literal("do_not_pick"),
      v.literal("uncategorized"),
    ),
  }).index("eventId", ["eventId"]).index("eventIdTeamNumber", ["eventId", "teamNumber"]),
  matches: defineTable({
    eventId: v.id("events"),
    tbaMatchKey: v.string(),
    matchNumber: v.number(),
    redTeamNumbers: v.array(v.number()),
    blueTeamNumbers: v.array(v.number()),
    scheduledTime: v.optional(v.number()),
  }).index("eventId", ["eventId"]).index("eventIdMatchNumber", ["eventId", "matchNumber"]),
  pitReports: defineTable({
    eventId: v.id("events"),
    teamId: v.id("teams"),
    scoutUserId: v.id("users"),
    // Older pit reports used these; new reports use the REBUILT fields below.
    scoreAnywhere: v.optional(v.boolean()),
    scoreSpecificSpots: v.optional(v.boolean()),
    shootOnMove: v.boolean(),
    climbLow: v.optional(v.boolean()),
    climbMid: v.optional(v.boolean()),
    climbHigh: v.optional(v.boolean()),
    shotRange: v.optional(v.union(v.literal("none"), v.literal("close"), v.literal("mid"), v.literal("long"))),
    groundIntake: v.optional(v.boolean()),
    humanPlayerIntake: v.optional(v.boolean()),
    fuelCapacity: v.optional(v.number()),
    autoFuelClaim: v.optional(v.number()),
    autoClimb: v.optional(v.boolean()),
    maxClimb: v.optional(v.union(v.literal("none"), v.literal("l1"), v.literal("l2"), v.literal("l3"))),
    traverse: v.union(v.literal("trench"), v.literal("bump"), v.literal("both"), v.literal("other")),
    drivetrain: v.string(),
    notes: v.optional(v.string()),
    photoIds: v.optional(v.array(v.id("_storage"))),
  }).index("teamId", ["teamId"]).index("eventId", ["eventId"]),
  techMessages: defineTable({
    eventId: v.id("events"),
    teamId: v.optional(v.id("teams")),
    createdBy: v.id("users"),
    message: v.string(),
    status: v.union(v.literal("open"), v.literal("resolved")),
    createdAt: v.number(),
    resolvedAt: v.optional(v.number()),
    resolvedBy: v.optional(v.id("users")),
  }).index("eventId", ["eventId"]).index("status", ["status"]),
  pitCrewItems: defineTable({
    eventId: v.id("events"),
    createdBy: v.id("users"),
    borrowerName: v.string(),
    borrowerTeam: v.string(),
    itemName: v.string(),
    notes: v.optional(v.string()),
    status: v.union(v.literal("borrowed"), v.literal("returned")),
    createdAt: v.number(),
    returnedAt: v.optional(v.number()),
    returnedBy: v.optional(v.id("users")),
  }).index("eventId", ["eventId"]).index("status", ["status"]),
  activityLogs: defineTable({
    eventId: v.optional(v.id("events")),
    actorUserId: v.id("users"),
    actorName: v.optional(v.string()),
    action: v.string(),
    targetUserId: v.optional(v.id("users")),
    details: v.optional(v.string()),
    createdAt: v.number(),
  }).index("eventId", ["eventId"]).index("actorUserId", ["actorUserId"]).index("createdAt", ["createdAt"]),
  matchReports: defineTable({
    eventId: v.id("events"),
    matchId: v.id("matches"),
    teamId: v.id("teams"),
    scoutUserId: v.id("users"),
    autoBallsScored: v.number(),
    teleopBallsScored: v.number(),
    autoNotes: v.optional(v.string()),
    teleopNotes: v.optional(v.string()),
    endgameResult: v.union(v.literal("none"), v.literal("low"), v.literal("mid"), v.literal("high")),
    endgameNotes: v.optional(v.string()),
    driverRating: v.number(),
    defenseRating: v.number(),
    autoClimb: v.optional(v.boolean()),
    accuracy: v.optional(v.union(v.literal("high"), v.literal("mid"), v.literal("low"))),
    fouls: v.optional(v.number()),
    tags: v.array(
      v.union(
        // Original tags (kept so older reports stay valid)
        v.literal("fast"),
        v.literal("accurate"),
        v.literal("good_driver"),
        v.literal("plays_defense"),
        v.literal("tippy"),
        v.literal("broke_down"),
        v.literal("inconsistent"),
        // REBUILT tags
        v.literal("fast_cycles"),
        v.literal("shoots_while_moving"),
        v.literal("fed_partners"),
        v.literal("played_defense"),
        v.literal("defended_well_against"),
        v.literal("wasted_inactive_hub"),
        v.literal("used_trench"),
        v.literal("tipped_over"),
        v.literal("disabled"),
        v.literal("no_show"),
      ),
    ),
  }).index("teamId", ["teamId"]).index("matchId", ["matchId"]).index("eventId", ["eventId"]).index("matchIdScoutUser", ["matchId", "scoutUserId"]),
  guestPasses: defineTable({
    code: v.string(),
    label: v.string(),
    includeNotes: v.boolean(),
    createdBy: v.id("users"),
    createdAt: v.number(),
    expiresAt: v.number(),
    revoked: v.boolean(),
    lastUsedAt: v.optional(v.number()),
  }).index("code", ["code"]).index("createdAt", ["createdAt"]),
  galleryPhotos: defineTable({
    eventId: v.optional(v.id("events")),
    storageId: v.id("_storage"),
    caption: v.optional(v.string()),
    uploadedBy: v.id("users"),
    createdAt: v.number(),
  }).index("createdAt", ["createdAt"]),
  picklists: defineTable({
    eventId: v.id("events"),
    ownerUserId: v.id("users"),
    name: v.string(),
    isPrimary: v.boolean(),
    source: v.union(v.literal("personal"), v.literal("primary"), v.literal("merged")),
  }).index("eventIdOwner", ["eventId", "ownerUserId"]),
  picklistEntries: defineTable({
    picklistId: v.id("picklists"),
    teamId: v.id("teams"),
    column: v.union(
      v.literal("tier1"),
      v.literal("tier2"),
      v.literal("tier3"),
      v.literal("do_not_pick"),
      v.literal("uncategorized"),
    ),
    order: v.number(),
  }).index("picklistId", ["picklistId"]).index("picklistIdColumn", ["picklistId", "column"]),
})
